assert( array( 'bt_bb_css_post_grid' ) === $GLOBALS['jpp_scripts']['jpp-deferred-post-grid']['deps'] );
assert( 'window.jppDeferredGridEnqueued=true;' === $GLOBALS['jpp_inline_scripts']['jpp-deferred-post-grid']['before'] );
