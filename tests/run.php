$aiko = new JPP\Integration_Aiko();
ob_start();
$aiko->mobile_hero_css();
$css = ob_get_clean();
assert( false !== strpos( $css, '@media(max-width:767px)' ) );
assert( false !== strpos( $css, '.bt_bb_section.jpp-has-mobile-lcp .bt_bb_background_image_holder' ) );
assert( false !== strpos( $css, 'contain-intrinsic-size:auto 800px' ) );
assert( false !== strpos( $css, '.bt_bb_wrapper>.bt_bb_section.bt_bb_animation_no_animation:nth-child(n+3)' ) );
assert( false !== strpos( $css, '.bt_bb_css_post_grid' ) );
assert( false !== strpos( $css, '.ti-widget,.wpcf7' ) );
$font_url = 'https://fonts.googleapis.com/css2?family=Poppins:ital,wght@0,100;0,300;0,400;1,700;1,900&display=swap';
$limited_font_url = $aiko->limit_front_page_font_axes( $font_url, 'boldthemes-fonts' );
assert( false !== strpos( $limited_font_url, 'Poppins:wght@300;400;500;700' ) );
$encoded_font_url = 'https://fonts.googleapis.com/css2?family=Poppins%3Aital%2Cwght%400%2C100%3B0%2C400%3B1%2C700';
assert( false !== strpos( $aiko->limit_front_page_font_axes( $encoded_font_url, 'bt_bb_google_fonts' ), 'Poppins:wght@300;400;500;700' ) );
assert( $font_url === $aiko->limit_front_page_font_axes( $font_url, 'other-fonts' ) );
assert( true === JPP\Compatibility::aiko() );
$GLOBALS['jpp_theme_version'] = '1.1.0';
assert( false === JPP\Compatibility::aiko() );
assert( $font_url === $aiko->limit_front_page_font_axes( $font_url, 'boldthemes-fonts' ) );
$GLOBALS['jpp_theme_version'] = '1.0.5';
assert( true === JPP\Compatibility::bold_builder() );
$verifier = new JPP\Admin_Dashboard();
$served = '<div class="bt_bb_parallax"></div><style>contain-intrinsic-size:auto 800px</style><picture class="jpp-mobile-lcp"></picture><div class="bt_bb_css_post_grid"></div><script>window.jppDeferredGridEnqueued=true</script><link href="https://fonts.googleapis.com/css2?family=Poppins:wght@300;400;500;700">';
$verification = $verifier->inspect_html( $served );
assert( true === $verification['passed'] );
assert( strlen( $served ) === $verification['bytes'] );
$failed_verification = $verifier->inspect_html( '<div class="bt_bb_parallax bt_bb_css_post_grid"></div><link href="https://fonts.googleapis.com/css2?family=Poppins:ital,wght@0,100;1,900">' );
assert( false === $failed_verification['passed'] );
$not_applicable = $verifier->inspect_html( '<style>contain-intrinsic-size:auto 800px</style>' );
assert( true === $not_applicable['checks']['hero'] );
assert( true === $not_applicable['checks']['deferred_grid'] );
assert( true === $not_applicable['checks']['font_axes'] );

